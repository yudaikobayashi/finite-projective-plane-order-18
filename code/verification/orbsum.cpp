// Independent completeness check of the net classes: for each class representative (normalised orthomorphism theta, theta(0)=0)
// compute its whole equivalence class {normalise(L(graph(theta)) + translation)} over L in (Z_P^* x S3) and all P translations,
// as an explicit set; verify (a) the representative is the lexicographic minimum of its class, (b) classes are pairwise disjoint
// (via a global hash set of all members), and print the sum of class sizes (must equal the number of normalised orthomorphisms).
// usage: orbsum P classesfile
#include <bits/stdc++.h>
using namespace std;
typedef unsigned long long u64;
#ifndef P
#define P 17
#endif
static inline int md(int v){ v%=P; return v<0?v+P:v; }
int main(int argc,char** argv){
  vector<array<int,P>> reps; { ifstream f(argv[1]); array<int,P> a; while(true){ bool ok=true; for(int i=0;i<P;i++) if(!(f>>a[i])) ok=false; if(!ok) break; reps.push_back(a);} }
  // S3 as matrices on (x,y), generated by (x,y)->(y,x) and (x,y)->(-x,y-x)
  typedef array<int,4> M; // (a,b,c,d): (x,y)->(a x+b y, c x+d y)
  auto mul=[&](M A,M B){ return M{md(A[0]*B[0]+A[1]*B[2]),md(A[0]*B[1]+A[1]*B[3]),md(A[2]*B[0]+A[3]*B[2]),md(A[2]*B[1]+A[3]*B[3])}; };
  set<M> S; M id={1,0,0,1}; S.insert(id); M g1={0,1,1,0}, g2={md(-1),0,md(-1),1};
  for(bool ch=true;ch;){ ch=false; vector<M> cur(S.begin(),S.end()); for(M A:cur) for(M g:{g1,g2}){ M C=mul(g,A); if(!S.count(C)){ S.insert(C); ch=true; } } }
  fprintf(stderr,"S3 size %zu\n",S.size());
  vector<M> grp; for(int m=1;m<P;m++) for(M A:S) grp.push_back({md(m*A[0]),md(m*A[1]),md(m*A[2]),md(m*A[3])});
  u64 sum=0; size_t bad_min=0,bad_ortho=0; 
  size_t dup=0; { auto c=reps; sort(c.begin(),c.end()); dup=c.size()-(unique(c.begin(),c.end())-c.begin()); } map<size_t,size_t> sizes;
  for(auto& th:reps){
    // check orthomorphism
    { set<int> a,b; for(int i=0;i<P;i++){ a.insert(th[i]); b.insert(md(th[i]-i)); } if((int)a.size()!=P||(int)b.size()!=P||th[0]!=0) bad_ortho++; }
    vector<array<unsigned char,P>> mem;
    for(auto& L:grp){ int ax[P],bx[P]; for(int a=0;a<P;a++){ ax[a]=md(L[0]*a+L[1]*th[a]); bx[a]=md(L[2]*a+L[3]*th[a]); }
      for(int o=0;o<P;o++){ array<unsigned char,P> t; t.fill(255); for(int a=0;a<P;a++) t[md(ax[a]-ax[o])]=md(bx[a]-bx[o]);
        mem.push_back(t); } }
    sort(mem.begin(),mem.end()); mem.erase(unique(mem.begin(),mem.end()),mem.end());
    // representative must be minimum
    array<unsigned char,P> r; for(int i=0;i<P;i++) r[i]=th[i];
    if(mem[0]!=r) bad_min++;
    sum+=mem.size(); sizes[mem.size()]++;
  }
  printf("classes %zu  sum of class sizes %llu  rep-not-min %zu  non-orthomorphism %zu  duplicate reps %zu\n",reps.size(),sum,bad_min,bad_ortho,dup);
  printf("class size histogram:"); for(auto&kv:sizes) printf(" %zu:%zu",kv.first,kv.second); printf("\n");
}
